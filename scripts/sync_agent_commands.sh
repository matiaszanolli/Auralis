#!/usr/bin/env bash
# Mirror the audit command suite for non-Claude agents (ZCode).
#
# .claude/commands/ is the single source of truth. This script:
#   1. copies every command (.md whose name is valid for ZCode — no leading
#      underscore, lowercase) into .agents/commands/, ZCode's workspace
#      command root;
#   2. regenerates the four .agents/skills/source-command-audit-* wrappers
#      (SKILL.md) whose bodies embed the shared _audit-* protocol files and
#      the deprecation/regression audits, so they can also auto-trigger as
#      skills.
#
# Usage:
#   scripts/sync_agent_commands.sh          refresh the mirror
#   scripts/sync_agent_commands.sh --check  exit 1 if the mirror is stale
#                                           (run by /audit-sync Phase 4)
set -euo pipefail
cd "$(dirname "$0")/.."

SRC=.claude/commands
DST=.agents/commands
SKILLS=.agents/skills

mode=refresh
[ "${1:-}" = "--check" ] && mode=check

stale=0
note() { printf '%s\n' "$*"; }

body_of() { # file minus its leading frontmatter block
    awk 'NR==1 && $0=="---" {fm=1; next} fm && $0=="---" {fm=0; next} !fm' "$1"
}

description_of() { # single-line quoted "description:" from the frontmatter
    sed -n '2,/^---$/p' "$1" | sed -n 's/^description:[[:space:]]*"//p' | sed 's/"$//'
}

sync_file() { # src dst
    if [ ! -f "$1" ]; then
        note "missing source: $1"
        exit 1
    fi
    if [ -f "$2" ] && cmp -s "$1" "$2"; then
        return
    fi
    if [ "$mode" = check ]; then
        note "stale: $2"
        stale=1
    else
        mkdir -p "$(dirname "$2")"
        cp "$1" "$2"
        note "updated: $2"
    fi
}

# 1. Commands.
mkdir -p "$DST"
declare -A mirrored=()
for src in "$SRC"/*.md; do
    name=$(basename "$src" .md)
    case "$name" in
        _*) continue ;; # shared protocol files; embedded in the skill wrappers below
    esac
    if ! [[ "$name" =~ ^[a-z0-9][a-z0-9_-]{0,63}$ ]]; then
        note "skip (not a valid ZCode command name): $name.md"
        continue
    fi
    mirrored[$name]=1
    sync_file "$src" "$DST/$name.md"
done

# Commands deleted from the source must not survive as orphans.
for dst in "$DST"/*.md; do
    [ -e "$dst" ] || continue
    name=$(basename "$dst" .md)
    if [ -z "${mirrored[$name]:-}" ]; then
        if [ "$mode" = check ]; then
            note "stale: $dst (no source)"
            stale=1
        else
            rm "$dst"
            note "removed: $dst"
        fi
    fi
done

# 2. Skill wrappers (skill name → source command, and its trigger line).
skill_src() {
    case "$1" in
        source-command-audit-common)      echo "_audit-common.md" ;;
        source-command-audit-severity)    echo "_audit-severity.md" ;;
        source-command-audit-deprecation) echo "audit-deprecation.md" ;;
        source-command-audit-regression)  echo "audit-regression.md" ;;
    esac
}

skill_intro() {
    case "$1" in
        source-command-audit-common)      echo "Use this skill for audit-protocol questions: project layout, severity framework, methodology, deduplication and finding format." ;;
        source-command-audit-severity)    echo "Use this skill to classify audit findings on the shared severity scale." ;;
        source-command-audit-deprecation) echo "Use this skill when the user asks for a deprecation audit of the codebase." ;;
        source-command-audit-regression)  echo "Use this skill when the user asks to verify that previously fixed issues have not regressed." ;;
    esac
}

for skill in source-command-audit-common source-command-audit-severity \
             source-command-audit-deprecation source-command-audit-regression; do
    src="$SRC/$(skill_src "$skill")"
    dst="$SKILLS/$skill/SKILL.md"
    tmp=$(mktemp)
    {
        printf -- '---\nname: "%s"\ndescription: "%s"\n---\n\n' "$skill" "$(description_of "$src")"
        printf '# %s\n\n' "$skill"
        printf '%s\n\n' "$(skill_intro "$skill")"
        printf 'Migrated from `.claude/commands/%s` — that file is the source of truth; this wrapper is regenerated by `scripts/sync_agent_commands.sh`.\n\n' "$(skill_src "$skill")"
        body_of "$src"
    } > "$tmp"
    if [ -f "$dst" ] && cmp -s "$tmp" "$dst"; then
        rm "$tmp"
    elif [ "$mode" = check ]; then
        rm "$tmp"
        note "stale: $dst"
        stale=1
    else
        mkdir -p "$(dirname "$dst")"
        mv "$tmp" "$dst"
        note "updated: $dst"
    fi
done

if [ "$mode" = check ] && [ "$stale" = 1 ]; then
    note "mirror is stale — run: scripts/sync_agent_commands.sh"
    exit 1
fi
note "mirror is up to date"
